"""Build cpldglue/gowinpins.py: Gowin package pin tables.

Usage (with Apycula installed, e.g. from yowasp-nextpnr-himbaechel-gowin):
  python tools/gowin_pins.py gowin_fpga.lib cpldglue/gowinpins.py

I/O pins: Apicula's chip databases (what nextpnr-himbaechel can use).
Pin names and types (power etc.): devbisme/KiCad-Schematic-Symbol-Libraries
gowin_fpga.lib (Unlicense). The two are cross-checked: every I/O pin's name
must start with the Apicula bel name.
"""
import re
import sys
import pprint

import apycula
from apycula import chipdb

LIB = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else None

# key -> (apicula db, apicula variant, apicula package, lib symbols to try)
PARTS = {
    "GW1NZ-1-QN32": ("GW1NZ-1", "GW1NZ-1", "QFN32", ["GW1NZ-1_FN32"]),
    "GW1N-4-QN48": ("GW1N-4", "GW1N-4", "QFN48", ["GW1N-2&2B&4&4B_QN48"]),
    "GW1N-4-QN88": ("GW1N-4", "GW1N-4", "QFN88", ["GW1N-2&2B&4&4B_QN88"]),
    "GW1N-4-LQ144": ("GW1N-4", "GW1N-4", "LQFP144", ["GW1N-2&2B&4&4B_LQ144"]),
    "GW1N-9-QN48": ("GW1N-9C", "GW1N-9C", "QFN48", ["GW1N-6&9_QN48"]),
    "GW1N-9-QN88": ("GW1N-9C", "GW1N-9C", "QFN88", ["GW1N-6&9_QN88"]),
    "GW1N-9-LQ144": ("GW1N-9C", "GW1N-9C", "LQFP144", ["GW1N-6&9_LQ144"]),
    "GW1NR-9-QN88P": ("GW1N-9C", "GW1NR-9C", "QFN88P", ["GW1NR-9_QN881", "GW1NR-9_QN882"]),
}

TYPES = {"B": "bidirectional", "I": "input", "O": "output", "W": "power_in",
         "w": "power_out", "P": "passive", "N": "no_connect", "C": "open_collector",
         "U": "unspecified", "T": "tri_state", "E": "open_emitter"}


def lib_symbols(path):
    out, cur = {}, None
    for line in open(path, encoding="utf-8", errors="replace"):
        if line.startswith("DEF "):
            cur = out.setdefault(line.split()[1], {})
        elif line.startswith("X ") and cur is not None:
            f = line.split()
            name, num, typ = f[1], f[2], f[11]
            cur[num] = (re.sub(r"\[\d+\]$", "", name), TYPES.get(typ, typ))
        elif line.startswith("ENDDEF"):
            cur = None
    return out


syms = lib_symbols(LIB)
dbs = {}
tables, report = {}, []
for key, (dbn, variant, pkg, cands) in PARTS.items():
    db = dbs.get(dbn) or dbs.setdefault(dbn, chipdb.load_chipdb(
        apycula.__path__[0] + f"/{dbn}.msgpack.xz"))
    ap = db.pinout[variant][pkg]
    best = None
    for c in cands:
        s = syms[c]
        bad = [p for p, (bel, _) in ap.items()
               if p not in s or s[p][0].split("/")[0] != bel]
        extra = [p for p, (n, _) in s.items()
                 if re.match(r"IO[LRTB]\d", n) and p not in ap]
        if best is None or len(bad) + len(extra) < best[0]:
            best = (len(bad) + len(extra), c, bad, extra)
    n, c, bad, extra = best
    s = syms[c]
    report.append(f"{key}: {c}: {len(ap)} I/O, {len(s)} pins, mismatched {bad}, "
                  f"lib I/O not in Apicula {extra}")
    pins = sorted(s, key=int)
    tables[key] = {
        "symbol": c,
        "io": sorted(int(p) for p in ap if p not in bad),
        "names": {int(p): s[p][0] for p in pins},
        "types": {int(p): s[p][1] for p in pins},
    }

print("\n".join(report))
if OUT:
    with open(OUT, "w", encoding="utf-8") as f:
        f.write('"""Gowin package pin tables (generated by tools/gowin_pins.py).\n\n'
                "I/O pins: Apicula's chip databases, i.e. the pins nextpnr-himbaechel can\n"
                "use. Pin names and types: gowin_fpga.lib from\n"
                "devbisme/KiCad-Schematic-Symbol-Libraries (Unlicense). Every I/O pin's\n"
                "name was checked against Apicula's bel name for it.\n"
                '"""\n# key -> {"symbol", "io": [I/O pins], "names": {pin: name}, '
                '"types": {pin: KiCad pin type}}\n')
        f.write("GOWIN_PINS = " + pprint.pformat(tables, width=100, compact=True) + "\n")
