"""Regenerate cpldglue/pintables.py from the Atmel ATF15xx BSDL files.

The BSDL files (Atmel copyright, not included here) are in the prjbureau
repository: https://github.com/whitequark/prjbureau/tree/main/bsdl

    python tools/bsdl_to_pins.py PATH/TO/bsdl > cpldglue/pintables.py

Each file's PIN_MAP lists every bonded pin: I/O, JTAG, the four dedicated
inputs, VCC and GND. Pins it doesn't list are no-connects. The function of
each dedicated input (GCLK1, OE1, GCLR, GCLK2/OE2) comes from the comment
above its boundary-scan cell.
"""
import re
import sys
from pathlib import Path

PKG = {"J44": "PLCC44", "A44": "TQFP44", "J68": "PLCC68", "J84": "PLCC84",
       "A100": "TQFP100", "Q100": "PQFP100", "Q160": "PQFP160"}
RENAME = {"GOE1": "OE1", "GCLK2": "GCLK2/OE2"}


def parse(path: Path) -> dict:
    t = path.read_text(errors="replace")
    m = re.search(r"PIN_MAP_STRING\s*:=(.*?);", t, re.S)
    body = "".join(re.findall(r'"([^"]*)"', m.group(1)))
    pins = {}
    for item in re.finditer(r"(\w+)\s*:\s*(\([^)]*\)|\d+)", body):
        pins[item.group(1)] = [int(x) for x in re.findall(r"\d+", item.group(2))]

    func, last = {}, None          # boundary-scan signal -> GCLK1 etc.
    for line in t.splitlines():
        c = re.match(r"\s*--.*,\s*(\w+)\s*$", line)
        if c:
            last = c.group(1)
        e = re.search(r"\(BC_\w+,\s*(DIN\(\d\)|IN\d+)\s*,", line)
        if e and last:
            func[e.group(1)] = last

    if "DIN" in pins:
        sig = {f"DIN({i + 1})": p for i, p in enumerate(pins["DIN"])}
    else:
        sig = {k: v[0] for k, v in pins.items() if re.fullmatch(r"IN\d+", k)}
    inputs = {RENAME.get(func[k], func[k]): p for k, p in sig.items()}
    jtag = {k: pins[k][0] for k in ("TDI", "TMS", "TCK", "TDO")}
    io = sorted([n for k, v in pins.items() if k.startswith("IO") for n in v]
                + list(jtag.values()))
    power = {p: "VCC" for p in pins["VCC"]}
    power.update({p: "GND" for p in pins["GND"]})
    total = int(re.search(r"(\d+)", PKG[re.match(r"\d+ASV?_(\w+)\.", path.name).group(1)]).group(1))
    used = set(io) | set(inputs.values()) | set(power)
    assert len(used) == len(io) + len(inputs) + len(power), f"{path.name}: overlap"
    return dict(io=io, inputs=dict(sorted(inputs.items(), key=lambda kv: kv[1])), jtag=jtag,
                power=dict(sorted(power.items())), total=total,
                nc=sorted(set(range(1, total + 1)) - used))


def main(src: str) -> None:
    tables = {}
    for f in sorted(Path(src).glob("*")):
        m = re.match(r"(\d+)(ASV?)_(\w+)\.bsd$", f.name, re.I)
        if not m:
            continue
        key = (f"ATF{m.group(1)}{m.group(2)}", PKG[m.group(3).upper()])
        tables[key] = parse(f)
    # AS and ASV parts share pinouts; emit one table per (family, package)
    # and fail loudly if that ever stops being true.
    out = {}
    for (dev, pkg), t in sorted(tables.items()):
        fam = dev[:7]                              # ATF1502 / ATF1504 / ATF1508
        if (fam, pkg) in out:
            assert out[(fam, pkg)] == t, f"{dev} {pkg} differs from the AS pinout"
        out[(fam, pkg)] = t

    w = sys.stdout.write
    w('"""ATF15xx pin tables, generated by tools/bsdl_to_pins.py from the Atmel\n'
      'BSDL files (one table per family and package; AS, ASL, ASV and ASVL parts\n'
      'share pinouts). Do not edit by hand."""\n\n')
    w("# (family, package) -> io (incl. JTAG), inputs, jtag, power, nc, total\n")
    w("TABLES = {\n")
    for (fam, pkg), t in out.items():
        w(f"    ({fam!r}, {pkg!r}): dict(\n")
        w(f"        total={t['total']},\n")
        w(f"        io={t['io']},\n")
        w(f"        inputs={t['inputs']},\n")
        w(f"        jtag={t['jtag']},\n")
        w(f"        power={t['power']},\n")
        w(f"        nc={t['nc']},\n")
        w("    ),\n")
    w("}\n")


if __name__ == "__main__":
    main(sys.argv[1])
